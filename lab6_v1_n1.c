#include <stdio.h>

int main() {
    int A[7][8];
    
    int i, j;
    
    printf("Матрица A (7x8):\n");
    printf("Правило: A[i][j] = 0 если (i+j) четное, иначе 1\n\n");
    
    for(i = 0; i < 7; i++) {          
        for(j = 0; j < 8; j++) {
            if((i + j) % 2 == 0) {
                A[i][j] = 0;
            }
            else {
                A[i][j] = 1;
            }

            printf("%d ", A[i][j]);
        }
        printf("\n");
    }
    
    printf("\nДемонстрация правила для нескольких элементов:\n");
    printf("A[0][0]: i=0, j=0, сумма=0 (четная) -> %d\n", A[0][0]);
    printf("A[0][1]: i=0, j=1, сумма=1 (нечетная) -> %d\n", A[0][1]);
    printf("A[1][0]: i=1, j=0, сумма=1 (нечетная) -> %d\n", A[1][0]);
    printf("A[1][1]: i=1, j=1, сумма=2 (четная) -> %d\n", A[1][1]);
    
    return 0;
}